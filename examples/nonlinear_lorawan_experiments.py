"""Real LoRaWAN protocol framing -- preamble, Hamming FEC, diagonal
interleaving, whitening, Gray coding, CRC16 (lora_phy's own encode()/
decode()) -- carried over THIS PROJECT's own nonlinear trajectory, not real
hardware's linear-only chirp.

examples/lorawan_experiments.py deliberately stayed at g=linear and said so
up front: "no real system generates a hyperbolic chirp." True, and that
file's whole point was cross-*validation* against real hardware, which is
correct to stay linear-only for. This file asks the other question: not
"does our math match real hardware," but "if a radio *could* transmit and
receive this project's own curved trajectory, would the rest of a real
LoRaWAN link -- the protocol semantics, not the PHY -- still work on top of
it?"

The answer falls out of how lora_phy itself is built, not from anything
new added here: `LoRaTransmitter.encode()` and `LoRaReceiver.decode()`
operate entirely on symbol *values* (0..M-1 chirp-shift integers) -- they
never touch a waveform sample. The only two lora_phy calls that actually
generate or demodulate a physical chirp are `modulate()`/`common.chirp`
(linear-only) and the receiver's internal dechirp -- and this project has
had its own general-purpose replacements for exactly those two calls since
the beginning: `chirp.py::symbol_waveform` (any g) and
`receiver.py::fft_correlation_demod` (already proven trajectory-agnostic,
14_ser_vs_snr_all_shapes.png). Swap those two in and the Hamming/CRC/
interleave/whiten layer comes along unmodified, because it was never
coupled to the linear-chirp assumption in the first place -- it only looks
coupled to it because every existing implementation of it happens to sit on
top of linear-chirp hardware.

`run_nonlinear_lorawan_packet` below is examples/lorawan_experiments.py's
own `run_lorawan_packet`, generalized: the one line that generated each
burst via `lora_phy.common.chirp` (linear-only) is replaced with this
project's own `symbol_waveform(cfg, m)` (respects cfg.g). Everything else
-- acquisition (sync.py::joint_cfo_symbol_search), per-burst tracking
(afc.py::full_symbol_cfo_estimate/AFCLoop/KalmanAFCLoop) -- was already
trajectory-agnostic; it just had never been pointed at a curved cfg inside
a real-framed packet before.

Run with: python examples/nonlinear_lorawan_experiments.py
"""
import os
import sys
import time

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from lorawan_experiments import N_PREAMBLE

try:
    from lora_phy import LoRaReceiver, LoRaTransmitter
    HAVE_LORA_PHY = True
except ImportError:
    HAVE_LORA_PHY = False

from nlfsc_lora.afc import AFCLoop, KalmanAFCLoop, _combine_acquisition, full_symbol_cfo_estimate, measurement_noise_for
from nlfsc_lora.channel import apply_cfo, apply_doppler_scale, awgn
from nlfsc_lora.chirp import ChirpConfig, symbol_waveform
from nlfsc_lora.paired_sweep import acquire_doppler_scale, correct_doppler_scale, reversed_trajectory
from nlfsc_lora.receiver import fft_correlation_demod
from nlfsc_lora.sync import correct_cfo, joint_cfo_symbol_search
from nlfsc_lora.trajectories import TRAJECTORIES, hyperbolic_center_freq

OUT_DIR = os.path.join(os.path.dirname(__file__), "output")
SF = 7
BANDWIDTH = 500e3
OVERSAMPLING = 4


def make_cfg(shape: str) -> ChirpConfig:
    g, _ = TRAJECTORIES[shape]
    f_center = hyperbolic_center_freq(BANDWIDTH) if shape == "hyperbolic" else 0.0
    return ChirpConfig(sf=SF, bandwidth=BANDWIDTH, sample_rate=OVERSAMPLING * BANDWIDTH, g=g, f_center=f_center)


def run_nonlinear_lorawan_packet(cfg, tx, rx, payload_len_bytes, true_cfo_sequence, snr_db, seed,
                                  loop=None, acquire_span=25000.0, acquire_step=250.0, track=True):
    """lorawan_experiments.run_lorawan_packet, generalized to any
    trajectory: the burst waveform is this project's own
    symbol_waveform(cfg, m) -- respecting cfg.g, hyperbolic included --
    instead of lora_phy's linear-only chirp construction.

    No grid-convention correction is needed here (lorawan_experiments.py's
    own half_bin_cfo): that existed only to reconcile this project's
    waveform convention with lora_phy's *different* one when a burst was
    generated by lora_phy but decoded by this project. Here both transmit
    and receive sides use this project's own convention throughout, so
    there is no mismatch to correct for.

    Returns (crc_ok, decoded_data_bytes, decoded_symbols)."""
    rng = np.random.default_rng(seed)
    payload_rng = np.random.default_rng(seed + 500_000)
    payload = payload_rng.integers(0, 256, payload_len_bytes, dtype=np.uint8)
    data_symbols_true = tx.encode(payload)  # real Hamming/interleave/whiten/Gray-coded stream
    all_true = np.concatenate([np.zeros(N_PREAMBLE, dtype=int), data_symbols_true.astype(int)])
    assert len(all_true) == len(true_cfo_sequence)

    loop = AFCLoop(gain=0.3) if loop is None else loop
    decoded = np.empty(len(all_true), dtype=int)
    acquire_candidates = np.arange(-acquire_span, acquire_span + acquire_step, acquire_step)
    acquire_results = []
    acquired_cfo = None

    for i, (m_true, cfo_true) in enumerate(zip(all_true, true_cfo_sequence)):
        cfo_tracked = loop.cfo_tracked
        burst = symbol_waveform(cfg, int(m_true))
        rx_burst = awgn(apply_cfo(burst, cfo_true, cfg.sample_rate), snr_db, rng)

        if i < N_PREAMBLE:
            m_hat, cfo_hat, _score = joint_cfo_symbol_search(rx_burst, cfg, acquire_candidates)
            decoded[i] = m_hat
            acquire_results.append((m_hat, cfo_hat))
            if i == N_PREAMBLE - 1:
                acquired_cfo = _combine_acquisition(acquire_results)
                if hasattr(loop, "set_acquired"):
                    loop.set_acquired(acquired_cfo)
                else:
                    loop.cfo_tracked = acquired_cfo
            continue

        correction = acquired_cfo if not track else cfo_tracked
        rx_corrected = correct_cfo(rx_burst, correction, cfg.sample_rate)
        m_hat = fft_correlation_demod(rx_corrected, cfg)
        decoded[i] = m_hat

        if track:
            cfo_residual_est, _pr = full_symbol_cfo_estimate(rx_corrected, cfg, m_hat)
            new_measurement = None if cfo_residual_est is None else cfo_tracked + cfo_residual_est
            loop.update(new_measurement)

    data_symbols = decoded[N_PREAMBLE:].astype(np.uint16)
    try:
        data, checksum = rx.decode(data_symbols)
        crc_ok = len(checksum) == 2 and list(data[payload_len_bytes:payload_len_bytes + 2]) == checksum
        decoded_bytes = data[:payload_len_bytes]
    except Exception:
        crc_ok, decoded_bytes = False, None
    return bool(crc_ok), decoded_bytes, decoded


def _packet_pass_rate(cfg, tx, rx, payload_len_bytes, cfo_fn, snr_range, n_trials, loop_factory=None):
    n_total = N_PREAMBLE + tx.encode(np.zeros(payload_len_bytes, dtype=np.uint8)).shape[0]
    true_cfo_sequence = cfo_fn(n_total)
    pass_rate = np.empty(len(snr_range))
    for i, snr_db in enumerate(snr_range):
        passes = 0
        for t in range(n_trials):
            loop = loop_factory() if loop_factory is not None else None
            ok, _bytes, _syms = run_nonlinear_lorawan_packet(cfg, tx, rx, payload_len_bytes, true_cfo_sequence,
                                                               snr_db, seed=t, loop=loop)
            passes += int(ok)
        pass_rate[i] = passes / n_trials
    return pass_rate


def test_correctness_noiseless():
    """A real, Hamming/CRC-coded LoRaWAN packet, physically carried on this
    project's own hyperbolic trajectory, under real Doppler, at high SNR:
    should pass CRC every time -- the basic end-to-end sanity check before
    any statistics."""
    payload_len = 12
    profiles_by_n = {}
    for shape in ["linear", "hyperbolic"]:
        cfg = make_cfg(shape)
        tx = LoRaTransmitter(SF, BANDWIDTH, cfg.sample_rate, has_header=True, coding_rate=4, enable_crc=True)
        rx = LoRaReceiver(rf_freq=868e6, spreading_factor=SF, bandwidth=BANDWIDTH, sample_rate=cfg.sample_rate)
        n_total = N_PREAMBLE + tx.encode(np.zeros(payload_len, dtype=np.uint8)).shape[0]
        seq = np.full(n_total, 20000.0)
        fails = 0
        n_trials = 15
        for t in range(n_trials):
            ok, _b, _s = run_nonlinear_lorawan_packet(cfg, tx, rx, payload_len, seq, snr_db=40.0, seed=t)
            fails += int(not ok)
        print(f"[{shape}] noiseless-ish (40dB), 20kHz CFO: {fails}/{n_trials} CRC failures")
        assert fails == 0, f"{shape} PHY should pass CRC every time at 40dB"


def experiment_pass_rate_linear_vs_hyperbolic():
    """The comparison: real LoRaWAN-framed packets, physically carried on a
    linear PHY (what real hardware would do) vs. this project's own
    hyperbolic PHY (what no real radio can do, but this project's own
    receiver can), under the same narrowband Doppler profiles
    examples/lorawan_experiments.py already characterized for linear alone.
    Narrowband CFO tolerance was already shown trajectory-independent at
    the correct symbol (NARRATIVE.md Sec5.1) -- this checks that holds once
    real channel coding is riding on top too, not just a single symbol's
    correlation loss."""
    payload_len = 12
    snr_range = np.arange(-20, 6, 2)
    n_trials = 60

    const_cfo_fn = lambda n: np.full(n, 20000.0)
    uav_cfo_fn = lambda n: (lambda t: -3000.0 * t / np.sqrt(t ** 2 + 90.0 ** 2))(np.linspace(-n / 2, n / 2, n))

    results = {}
    for shape in ["linear", "hyperbolic"]:
        cfg = make_cfg(shape)
        tx = LoRaTransmitter(SF, BANDWIDTH, cfg.sample_rate, has_header=True, coding_rate=4, enable_crc=True)
        rx = LoRaReceiver(rf_freq=868e6, spreading_factor=SF, bandwidth=BANDWIDTH, sample_rate=cfg.sample_rate)
        for profile_name, cfo_fn in [("constant 20kHz", const_cfo_fn), ("UAV reversal", uav_cfo_fn)]:
            t0 = time.time()
            pass_rate = _packet_pass_rate(cfg, tx, rx, payload_len, cfo_fn, snr_range, n_trials,
                                           loop_factory=lambda: KalmanAFCLoop(measurement_noise=measurement_noise_for(cfg)))
            print(f"[{shape}/{profile_name}] done in {time.time()-t0:.1f}s")
            results[(shape, profile_name)] = pass_rate

    return snr_range, results


def plot_nonlinear_lorawan_findings(snr_range, results):
    os.makedirs(OUT_DIR, exist_ok=True)
    profiles = ["constant 20kHz", "UAV reversal"]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.8))
    for ax, profile_name in zip(axes, profiles):
        for shape in ["linear", "hyperbolic"]:
            ax.plot(snr_range, results[(shape, profile_name)], marker="o", ms=4, label=f"{shape} PHY")
        ax.set(xlabel="SNR (dB)", ylabel="packet CRC pass rate", ylim=(-0.05, 1.05), title=profile_name)
        ax.invert_xaxis()
        ax.legend(fontsize=8)
    fig.suptitle("Real LoRaWAN-framed packets on a linear PHY (what real hardware does) vs. this\n"
                 "project's own hyperbolic PHY (what no real radio can do, but this receiver can)")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "30_nonlinear_lorawan_pass_rate.png"), dpi=150)
    plt.close(fig)


def make_cfg_pair(q: float = 1.0 / 3.0):
    """Up-sweep and down-sweep hyperbolic ChirpConfigs sharing one band --
    packet_experiments.py's own Test 4 construction, for the paired-sweep
    preamble nlfsc_lora.paired_sweep needs."""
    g_up, _ = TRAJECTORIES["hyperbolic"]
    g_down = reversed_trajectory(g_up)
    f_center = hyperbolic_center_freq(BANDWIDTH, q)
    cfg_up = ChirpConfig(sf=SF, bandwidth=BANDWIDTH, sample_rate=OVERSAMPLING * BANDWIDTH, g=g_up, f_center=f_center)
    cfg_down = ChirpConfig(sf=SF, bandwidth=BANDWIDTH, sample_rate=OVERSAMPLING * BANDWIDTH, g=g_down, f_center=f_center)
    return cfg_up, cfg_down


def run_wideband_nonlinear_lorawan_packet(cfg_up, cfg_down, tx, rx, payload_len_bytes, alpha_true, q,
                                           snr_db, seed, correct=True):
    """The scenario no real LoRaWAN radio can survive at all, corrected the
    way only a hyperbolic PHY can be: a wideband Doppler *time-scale*
    (channel.py::apply_doppler_scale, not a narrowband CFO), applied to a
    real, Hamming FEC + interleaved + whitened + Gray-coded + CRC16-checked
    packet (lora_phy's own encode()/decode()) physically carried on this
    project's own hyperbolic trajectory. Acquired from a single paired
    up-sweep/down-sweep preamble pair (nlfsc_lora.paired_sweep, the DHFM-
    style real active-sonar technique -- NARRATIVE.md's "Building the Same
    Thing"), then every payload burst is corrected with the same estimate
    before an ordinary decode.

    `correct=False` skips the paired-sweep correction entirely (payload
    bursts decoded straight from the Doppler-scaled signal) -- the
    uncorrected baseline every trajectory shape fails at past a small
    alpha (08_lora_ser_vs_doppler_scale.png), included here to make the
    contrast concrete rather than assumed. A linear PHY has no correction
    mechanism to even attempt: paired_sweep's closed form is derived from
    HFM's own exact self-similarity theorem (Sec5.2), which a linear chirp
    does not have, so this scenario is not just harder for real hardware --
    it is a capability real hardware structurally cannot have at all,
    corrected or not.

    Returns (crc_ok, decoded_data_bytes, alpha_hat)."""
    rng = np.random.default_rng(seed)
    payload_rng = np.random.default_rng(seed + 500_000)
    payload = payload_rng.integers(0, 256, payload_len_bytes, dtype=np.uint8)
    data_symbols_true = tx.encode(payload)

    rx_pre_up = awgn(apply_doppler_scale(symbol_waveform(cfg_up, 0), alpha_true), snr_db, rng)
    rx_pre_down = awgn(apply_doppler_scale(symbol_waveform(cfg_down, 0), alpha_true), snr_db, rng)
    alpha_hat = acquire_doppler_scale(rx_pre_up, rx_pre_down, cfg_up, cfg_down, q) if correct else 1.0

    decoded = np.empty(len(data_symbols_true), dtype=int)
    for i, m_true in enumerate(data_symbols_true):
        rx_burst = awgn(apply_doppler_scale(symbol_waveform(cfg_up, int(m_true)), alpha_true), snr_db, rng)
        rx_corrected = correct_doppler_scale(rx_burst, alpha_hat) if correct else rx_burst
        decoded[i] = fft_correlation_demod(rx_corrected, cfg_up)

    try:
        data, checksum = rx.decode(decoded.astype(np.uint16))
        crc_ok = len(checksum) == 2 and list(data[payload_len_bytes:payload_len_bytes + 2]) == checksum
        decoded_bytes = data[:payload_len_bytes]
    except Exception:
        crc_ok, decoded_bytes = False, None
    return bool(crc_ok), decoded_bytes, alpha_hat


def test_wideband_correctness_noiseless():
    """alpha=1.05 is comfortably past this configuration's own half-bin
    failure threshold (~1.004, 08_lora_ser_vs_doppler_scale.png) -- an
    uncorrected receiver should fail on essentially every packet; the
    paired-sweep-corrected one should pass every time."""
    q = 1.0 / 3.0
    cfg_up, cfg_down = make_cfg_pair(q)
    tx = LoRaTransmitter(SF, BANDWIDTH, cfg_up.sample_rate, has_header=True, coding_rate=4, enable_crc=True)
    rx = LoRaReceiver(rf_freq=868e6, spreading_factor=SF, bandwidth=BANDWIDTH, sample_rate=cfg_up.sample_rate)
    alpha_true = 1.05
    payload_len = 12
    n_trials = 15

    fails_corrected = fails_uncorrected = 0
    for t in range(n_trials):
        ok_c, _b, _a = run_wideband_nonlinear_lorawan_packet(cfg_up, cfg_down, tx, rx, payload_len, alpha_true, q,
                                                               snr_db=40.0, seed=t, correct=True)
        ok_u, _b, _a = run_wideband_nonlinear_lorawan_packet(cfg_up, cfg_down, tx, rx, payload_len, alpha_true, q,
                                                               snr_db=40.0, seed=t, correct=False)
        fails_corrected += int(not ok_c)
        fails_uncorrected += int(not ok_u)
    print(f"wideband alpha={alpha_true}: corrected {fails_corrected}/{n_trials} failures, "
          f"uncorrected {fails_uncorrected}/{n_trials} failures")
    assert fails_corrected == 0
    assert fails_uncorrected >= 0.9 * n_trials


def experiment_wideband_pass_rate_vs_snr():
    """Packet CRC pass rate vs. SNR at alpha=1.05: paired-sweep-corrected
    hyperbolic PHY vs. uncorrected -- the wideband-Doppler-scale
    counterpart to experiment_pass_rate_linear_vs_hyperbolic's narrowband
    comparison. There is no "linear PHY" curve here: a linear chirp has no
    correction mechanism for this channel model at all (see this function's
    own module-level docstring), so "uncorrected" already stands in for
    what every real LoRaWAN radio's best case looks like under this exact
    channel condition."""
    q = 1.0 / 3.0
    cfg_up, cfg_down = make_cfg_pair(q)
    tx = LoRaTransmitter(SF, BANDWIDTH, cfg_up.sample_rate, has_header=True, coding_rate=4, enable_crc=True)
    rx = LoRaReceiver(rf_freq=868e6, spreading_factor=SF, bandwidth=BANDWIDTH, sample_rate=cfg_up.sample_rate)
    alpha_true = 1.05
    payload_len = 12
    snr_range = np.arange(-20, 6, 2)
    n_trials = 60

    results = {}
    for correct in [True, False]:
        t0 = time.time()
        pass_rate = np.empty(len(snr_range))
        for i, snr_db in enumerate(snr_range):
            passes = 0
            for t in range(n_trials):
                ok, _b, _a = run_wideband_nonlinear_lorawan_packet(cfg_up, cfg_down, tx, rx, payload_len,
                                                                     alpha_true, q, snr_db, seed=t, correct=correct)
                passes += int(ok)
            pass_rate[i] = passes / n_trials
        label = "paired-sweep corrected" if correct else "uncorrected"
        print(f"[{label}] done in {time.time()-t0:.1f}s")
        results[label] = pass_rate

    return snr_range, results


def plot_wideband_findings(snr_range, results):
    os.makedirs(OUT_DIR, exist_ok=True)
    fig, ax = plt.subplots(figsize=(7, 4.8))
    for label, pass_rate in results.items():
        ax.plot(snr_range, pass_rate, marker="o", ms=4, label=label)
    ax.set(xlabel="SNR (dB)", ylabel="packet CRC pass rate", ylim=(-0.05, 1.05),
           title="Real LoRaWAN-framed packet, wideband Doppler scale (alpha=1.05)\n"
                 "hyperbolic PHY, no real radio can attempt this at all")
    ax.invert_xaxis()
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "31_nonlinear_lorawan_wideband_scale.png"), dpi=150)
    plt.close(fig)


def main():
    if not HAVE_LORA_PHY:
        print("lora_phy is not installed (pip install .[refcheck]) -- skipping nonlinear-LoRaWAN experiments.")
        return
    test_correctness_noiseless()
    snr_range, results = experiment_pass_rate_linear_vs_hyperbolic()
    plot_nonlinear_lorawan_findings(snr_range, results)

    test_wideband_correctness_noiseless()
    snr_range_wb, results_wb = experiment_wideband_pass_rate_vs_snr()
    plot_wideband_findings(snr_range_wb, results_wb)
    print(f"Wrote figures to {OUT_DIR}")


if __name__ == "__main__":
    main()
